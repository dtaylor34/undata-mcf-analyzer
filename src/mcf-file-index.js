/**
 * Get all file options for selection
 */
export function getAllFiles() {
  const files = [];
  
  // ILO files
  MCF_FILE_INDEX.ilo.files.forEach(file => {
    files.push({
      ...file,
      org: 'ilo',
      orgName: MCF_FILE_INDEX.ilo.name,
      emoji: MCF_FILE_INDEX.ilo.emoji,
      displayName: `${MCF_FILE_INDEX.ilo.emoji} ILO / ${file.name}`
    });
  });
  
  // SDG files (with versions)
  Object.entries(MCF_FILE_INDEX.sdg.versions).forEach(([versionKey, version]) => {
    version.files.forEach(file => {
      files.push({
        ...file,
        org: 'sdg',
        version: versionKey,
        versionName: version.name,
        orgName: MCF_FILE_INDEX.sdg.name,
        emoji: MCF_FILE_INDEX.sdg.emoji,
        displayName: `${MCF_FILE_INDEX.sdg.emoji} SDG ${version.name} / ${file.name}`
      });
    });
  });
  
  // UNICEF files
  MCF_FILE_INDEX.unicef.files.forEach(file => {
    files.push({
      ...file,
      org: 'unicef',
      orgName: MCF_FILE_INDEX.unicef.name,
      emoji: MCF_FILE_INDEX.unicef.emoji,
      displayName: `${MCF_FILE_INDEX.unicef.emoji} UNICEF / ${file.name}`
    });
  });
  
  // WHO files
  MCF_FILE_INDEX.who.files.forEach(file => {
    files.push({
      ...file,
      org: 'who',
      orgName: MCF_FILE_INDEX.who.name,
      emoji: MCF_FILE_INDEX.who.emoji,
      displayName: `${MCF_FILE_INDEX.who.emoji} WHO / ${file.name}`
    });
  });
  
  return files;
}

