/**
 * Convert country code to full name
 * @param {string} code - ISO 3166-1 alpha-3 country code
 * @returns {string} Full country name or the original code if not found
 */
export function getCountryName(code) {
  if (!code) return '';
  const upperCode = code.toUpperCase();
  return COUNTRY_NAMES[upperCode] || code;
}

/**
 * Convert country dcid to full name
 * Handles formats like "country/USA" or "USA"
 * @param {string} dcid - Country dcid or code
 * @returns {string} Full country name
 */
export function getCountryNameFromDcid(dcid) {
  if (!dcid) return '';
  
  // Extract code from dcid format (e.g., "country/USA" -> "USA")
  const code = dcid.includes('/') ? dcid.split('/').pop() : dcid;
  return getCountryName(code);
}

